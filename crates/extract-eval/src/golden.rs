//! The SynthDay golden format (`synthday/v1`, FR-EV-02).
//!
//! One file is one synthetic work day: who the user is, what SHOGUN saw (timestamped events with
//! the source, app, window and text capture would record), and the state rows a correct extractor
//! should produce from them (`gold`). Every gold row names the event ids that evidence it and the
//! confidence band a calibrated extractor should give it, so the scorer can check provenance and
//! calibration as well as content.
//!
//! Golden files are **generated, never hand-edited**: `tests/gate.rs` regenerates every day from
//! [`crate::generate::GOLDEN_SPECS`] and fails if the checked-in file differs. That is what keeps
//! real data out structurally — the only text that can appear is template text from
//! `src/templates.rs` with names from its fictional pools.

use std::collections::BTreeMap;

use serde::{Deserialize, Serialize};

/// Format tag written into every golden file. Bump it when the shape changes.
pub const FORMAT: &str = "synthday/v1";

/// A synthetic work day.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct SynthDay {
    pub format: String,
    pub id: String,
    pub generator: GeneratorInfo,
    pub persona: Persona,
    /// The persona's local calendar date, `YYYY-MM-DD`.
    pub date: String,
    pub events: Vec<Event>,
    pub gold: Vec<GoldItem>,
}

/// How the day was produced, so it can be regenerated byte-for-byte.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct GeneratorInfo {
    pub seed: u64,
    pub template_set: String,
    /// Templates the spec forces into the day (bug repros, traps), in addition to seeded picks.
    pub required_templates: Vec<String>,
}

/// The synthetic user whose day this is.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Persona {
    pub id: String,
    pub name: String,
    pub role: String,
    pub org: String,
    /// `en` or `ja` — the language the templates for this persona are written in.
    pub lang: String,
    /// Fixed UTC offset of the persona's clock. Due dates are read against it.
    pub utc_offset_secs: i32,
}

/// One thing SHOGUN saw. `source` uses the event_log source names (`capture`, `gmail`, `gcal`,
/// `slack`, `meeting`), so the Batch source filter applies to it exactly as in the product.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct Event {
    pub id: i64,
    pub ts_ms: i64,
    /// `HH:MM` on the persona's clock — for people reading the file; the scorer uses `ts_ms`.
    pub local_time: String,
    pub source: String,
    pub app: String,
    pub window: String,
    pub text: String,
    /// The template that produced this event (a `trap_*` template produces no gold).
    pub template: String,
}

/// The state tables the extraction eval scores (the ones FR-ST-02 requires provenance for).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum Table {
    People,
    Projects,
    Commitments,
    OpenLoops,
}

impl Table {
    pub const ALL: [Table; 4] = [Table::People, Table::Projects, Table::Commitments, Table::OpenLoops];

    pub fn as_str(self) -> &'static str {
        match self {
            Table::People => "people",
            Table::Projects => "projects",
            Table::Commitments => "commitments",
            Table::OpenLoops => "open_loops",
        }
    }

    /// The fields scored for this table. `description` / `name` is the key a prediction is matched
    /// on; the others are scored once matched.
    pub fn fields(self) -> &'static [&'static str] {
        match self {
            Table::People | Table::Projects => &["name"],
            Table::Commitments => &["direction", "description", "due"],
            Table::OpenLoops => &["kind", "description"],
        }
    }

    /// The field a prediction is matched to gold on.
    pub fn key_field(self) -> &'static str {
        match self {
            Table::People | Table::Projects => "name",
            Table::Commitments | Table::OpenLoops => "description",
        }
    }
}

/// A confidence band, named as in `shogun_fusion::confidence` (FR-ST-20).
#[derive(Debug, Clone, Copy, PartialEq, Eq, PartialOrd, Ord, Hash, Serialize, Deserialize)]
#[serde(rename_all = "snake_case")]
pub enum BandLabel {
    Low,
    Medium,
    High,
}

impl BandLabel {
    pub const ALL: [BandLabel; 3] = [BandLabel::Low, BandLabel::Medium, BandLabel::High];

    pub fn of(confidence: f64) -> BandLabel {
        match shogun_fusion::confidence::band(confidence) {
            shogun_fusion::confidence::Band::Low => BandLabel::Low,
            shogun_fusion::confidence::Band::Medium => BandLabel::Medium,
            shogun_fusion::confidence::Band::High => BandLabel::High,
        }
    }

    pub fn as_str(self) -> &'static str {
        match self {
            BandLabel::Low => "low",
            BandLabel::Medium => "medium",
            BandLabel::High => "high",
        }
    }

    /// The accuracy a band promises downstream. FR-ST-20: High is used as fact, Medium is passed
    /// as "possibly", Low is excluded. So a prediction labelled High should be right at least as
    /// often as the High floor (0.8) and a Medium one at least as often as the Medium floor (0.5);
    /// Low promises nothing. Read off `band()` rather than restated, so the two cannot drift.
    pub fn promised_accuracy(self) -> Option<f64> {
        match self {
            BandLabel::Low => None,
            BandLabel::Medium => Some(lowest_confidence_in(BandLabel::Medium)),
            BandLabel::High => Some(lowest_confidence_in(BandLabel::High)),
        }
    }
}

/// The smallest confidence (at 0.001 resolution) that `shogun_fusion::confidence::band` puts in
/// `label`. Used so the calibration table's bucket edges are the product's, not a copy.
pub fn lowest_confidence_in(label: BandLabel) -> f64 {
    (0..=1000)
        .map(|i| f64::from(i) / 1000.0)
        .find(|c| BandLabel::of(*c) == label)
        .unwrap_or(1.0)
}

/// One row a correct extractor should produce.
#[derive(Debug, Clone, PartialEq, Serialize, Deserialize)]
#[serde(deny_unknown_fields)]
pub struct GoldItem {
    pub id: String,
    pub table: Table,
    /// Field values, keyed by [`Table::fields`]. An absent field means "no value" (e.g. a
    /// commitment with no stated deadline has no `due`).
    pub fields: BTreeMap<String, String>,
    /// The band a calibrated extractor should assign: `medium` for one explicit statement,
    /// `high` for a fact evidenced repeatedly (FR-ST-20/21 reserve High for that).
    pub expected_band: BandLabel,
    /// Event ids that evidence this row. A prediction must cite at least one to match it.
    pub evidence: Vec<i64>,
}

impl SynthDay {
    pub fn event(&self, id: i64) -> Option<&Event> {
        self.events.iter().find(|e| e.id == id)
    }

    /// Serialise exactly as the checked-in golden files are written (2-space pretty JSON with a
    /// trailing newline), so regeneration can be compared byte-for-byte.
    pub fn to_json(&self) -> Result<String, serde_json::Error> {
        let mut s = serde_json::to_string_pretty(self)?;
        s.push('\n');
        Ok(s)
    }

    pub fn from_json(s: &str) -> Result<SynthDay, serde_json::Error> {
        serde_json::from_str(s)
    }
}

/// The checked-in golden days, embedded so every consumer (this crate's tests, shogun-core's
/// `db` test target, the report binary) reads the same bytes without a path lookup.
pub const GOLDEN_FILES: &[(&str, &str)] = &[
    ("day-01-eng-lead", include_str!("../goldens/day-01-eng-lead.json")),
    ("day-02-ops-traps", include_str!("../goldens/day-02-ops-traps.json")),
    ("day-03-ja-pm", include_str!("../goldens/day-03-ja-pm.json")),
    ("day-04-mixed", include_str!("../goldens/day-04-mixed.json")),
    ("day-05-ja-dashboard-noise", include_str!("../goldens/day-05-ja-dashboard-noise.json")),
    ("day-06-en-dashboard-noise", include_str!("../goldens/day-06-en-dashboard-noise.json")),
];

/// Parse every checked-in golden day.
pub fn golden_days() -> Result<Vec<SynthDay>, serde_json::Error> {
    GOLDEN_FILES.iter().map(|(_, json)| SynthDay::from_json(json)).collect()
}
